"""
Tire mechanics and transient thermal balance module.
Implements:
1. Load-sensitive friction coefficient mu(Fz)
2. Bell-curve thermal friction efficiency mu(T_tire)
3. Combined longitudinal/lateral grip friction circle (Pacejka ellipse)
4. Forward-Euler numerical integration of tire thermal state ODE
"""

import numpy as np
from dataclasses import dataclass
from .params import VehicleParams


@dataclass
class TireState:
    t_tire: float            # Bulk temperature (°C)
    mu_eff: float            # Effective combined friction coefficient
    f_z: float               # Total normal load (N)
    f_grip_max: float        # Total maximum adhesion capability (N)
    f_x_max_avail: float     # Maximum available longitudinal force after lateral allocation (N)
    f_y_demand: float        # Current lateral cornering force demand (N)
    q_gen_rate: float        # Heat generation rate (Watts)
    q_cool_rate: float       # Convective cooling rate (Watts)


class TireModel:
    def __init__(self, params: VehicleParams):
        self.p = params
        self.t_tire = params.t_tire_initial

    def reset(self, initial_temp: float = None):
        self.t_tire = initial_temp if initial_temp is not None else self.p.t_tire_initial

    def compute_mu(self, f_z: float, t_tire: float) -> float:
        """
        Computes friction coefficient mu(T_tire, F_z).
        Includes tire load sensitivity degradation and thermal window penalty.
        """
        # Load sensitivity: mu drops as normal load F_z rises above baseline
        delta_fz = max(0.0, f_z - self.p.fz_ref)
        mu_load = self.p.mu_peak * (1.0 - self.p.load_sensitivity * delta_fz)
        mu_load = max(0.85, mu_load)

        # Thermal operating window: realistic slick tire efficiency
        # Peaks at 100°C, retains ~70% grip at cold ambient 25°C, degrades if blistering > 125°C
        t_diff = t_tire - self.p.t_tire_opt
        thermal_factor = 0.70 + 0.30 * np.exp(-0.5 * (t_diff / self.p.t_tire_sigma) ** 2)

        # Extreme overheating penalty (blistering / degradation above 125°C)
        if t_tire > 125.0:
            thermal_factor *= max(0.65, 1.0 - 0.015 * (t_tire - 125.0))

        mu_eff = mu_load * thermal_factor
        return float(mu_eff)

    def evaluate_state(self, v: float, a_lat: float, f_downforce: float, grade_rad: float = 0.0) -> TireState:
        """
        Calculates available grip and friction ellipse budget for given speed and lateral acceleration.
        """
        # Normal vertical force on all 4 tires
        f_z = (self.p.total_mass * self.p.gravity * np.cos(grade_rad)) + f_downforce
        f_z = max(1000.0, f_z)

        # Effective friction coefficient
        mu = self.compute_mu(f_z, self.t_tire)

        # Maximum grip vector magnitude (Pacejka friction envelope limit)
        f_grip_max = mu * f_z

        # Lateral force needed for current cornering demand, bounded physically by peak tire adhesion
        f_y_demand_unbounded = self.p.total_mass * abs(a_lat)
        f_y_actual = min(f_y_demand_unbounded, f_grip_max)

        # Friction ellipse constraint: (Fx / Fx_max)^2 + (Fy / Fy_max)^2 <= 1
        # Leave remaining longitudinal friction budget for braking/traction
        f_x_max_avail = np.sqrt(max(0.0, f_grip_max ** 2 - f_y_actual ** 2))

        return TireState(
            t_tire=self.t_tire,
            mu_eff=mu,
            f_z=f_z,
            f_grip_max=f_grip_max,
            f_x_max_avail=f_x_max_avail,
            f_y_demand=f_y_actual,
            q_gen_rate=0.0,
            q_cool_rate=0.0
        )

    def step_thermal_ode(self, v: float, f_x_applied: float, f_y_applied: float, dt: float, f_z: float = 8000.0) -> float:
        """
        Integrates tire bulk temperature dT_tire/dt via Forward-Euler:
        dT/dt = (Q_gen - Q_cool) / C_thermal
        """
        f_total = np.hypot(f_x_applied, f_y_applied)

        # Frictional dissipation power generated by tire contact patch shear + carcass rolling flexing
        q_slip = self.p.k_heat_gen_slip * (f_total * (v + 5.0) * 0.08)
        q_carcass = 0.25 * (self.p.c_rr * f_z * v)
        q_gen = q_slip + q_carcass

        # Convective cooling to ambient air over tire surface and wheel rims
        h_cool = self.p.h_cool_base + self.p.h_cool_speed_gain * v
        q_cool = h_cool * (self.t_tire - self.p.ambient_temp)

        # Forward-Euler step
        dt_tire = ((q_gen - q_cool) / self.p.c_tire_thermal) * dt
        self.t_tire += dt_tire

        # Floor at ambient temperature
        self.t_tire = max(self.p.ambient_temp, self.t_tire)
        return self.t_tire
